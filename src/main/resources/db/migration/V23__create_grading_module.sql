CREATE TABLE grade_scales (
    id BIGINT AUTO_INCREMENT PRIMARY KEY,
    school_id BIGINT NOT NULL,
    academic_year_id BIGINT NOT NULL,
    name VARCHAR(100) NOT NULL,
    active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at DATETIME(6) NOT NULL,
    updated_at DATETIME(6),
    CONSTRAINT fk_grade_scale_school FOREIGN KEY (school_id) REFERENCES schools(id),
    CONSTRAINT fk_grade_scale_academic_year FOREIGN KEY (academic_year_id) REFERENCES academic_years(id),
    CONSTRAINT uk_grade_scale_school_name_year UNIQUE (school_id, name, academic_year_id),
    CONSTRAINT chk_grade_scale_active CHECK (active IN (TRUE, FALSE)),
    INDEX idx_grade_scale_school (school_id),
    INDEX idx_grade_scale_academic_year (academic_year_id)
);

CREATE TABLE grade_scale_ranges (
    id BIGINT AUTO_INCREMENT PRIMARY KEY,
    scale_id BIGINT NOT NULL,
    letter_grade VARCHAR(10) NOT NULL,
    gpa DECIMAL(4,2) NOT NULL,
    min_percentage DECIMAL(5,2) NOT NULL,
    max_percentage DECIMAL(5,2) NOT NULL,
    description VARCHAR(255) NULL,
    sort_order INT NOT NULL,
    created_at DATETIME(6) NOT NULL,
    updated_at DATETIME(6),
    CONSTRAINT fk_grade_range_scale FOREIGN KEY (scale_id) REFERENCES grade_scales(id) ON DELETE CASCADE,
    CONSTRAINT uk_grade_range_scale_letter UNIQUE (scale_id, letter_grade),
    CONSTRAINT chk_grade_range_percentages CHECK (min_percentage >= 0 AND max_percentage <= 100 AND max_percentage > min_percentage),
    CONSTRAINT chk_grade_range_gpa CHECK (gpa >= 0),
    INDEX idx_grade_range_scale (scale_id)
);

CREATE TABLE assessment_types (
    id BIGINT AUTO_INCREMENT PRIMARY KEY,
    school_id BIGINT NOT NULL,
    name VARCHAR(100) NOT NULL,
    code VARCHAR(50) NOT NULL,
    sort_order INT NOT NULL,
    active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at DATETIME(6) NOT NULL,
    updated_at DATETIME(6),
    CONSTRAINT fk_assessment_type_school FOREIGN KEY (school_id) REFERENCES schools(id),
    CONSTRAINT uk_assessment_type_school_code UNIQUE (school_id, code),
    CONSTRAINT chk_assessment_type_active CHECK (active IN (TRUE, FALSE)),
    INDEX idx_assessment_type_school (school_id)
);

CREATE TABLE assessment_papers (
    id BIGINT AUTO_INCREMENT PRIMARY KEY,
    assessment_type_id BIGINT NOT NULL,
    name VARCHAR(100) NOT NULL,
    code VARCHAR(50) NOT NULL,
    weight DECIMAL(10,2) NOT NULL,
    max_score DECIMAL(10,2) NOT NULL,
    sort_order INT NOT NULL,
    created_at DATETIME(6) NOT NULL,
    updated_at DATETIME(6),
    CONSTRAINT fk_assessment_paper_type FOREIGN KEY (assessment_type_id) REFERENCES assessment_types(id) ON DELETE CASCADE,
    CONSTRAINT uk_assessment_paper_type_code UNIQUE (assessment_type_id, code),
    CONSTRAINT chk_assessment_paper_weight CHECK (weight >= 0),
    CONSTRAINT chk_assessment_paper_max_score CHECK (max_score > 0),
    INDEX idx_assessment_paper_type (assessment_type_id)
);

CREATE TABLE subject_assessments (
    id BIGINT AUTO_INCREMENT PRIMARY KEY,
    school_id BIGINT NOT NULL,
    term_id BIGINT NOT NULL,
    subject_id BIGINT NOT NULL,
    assessment_type_id BIGINT NOT NULL,
    active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at DATETIME(6) NOT NULL,
    updated_at DATETIME(6),
    CONSTRAINT fk_subject_assessment_school FOREIGN KEY (school_id) REFERENCES schools(id),
    CONSTRAINT fk_subject_assessment_term FOREIGN KEY (term_id) REFERENCES terms(id),
    CONSTRAINT fk_subject_assessment_subject FOREIGN KEY (subject_id) REFERENCES subjects(id),
    CONSTRAINT fk_subject_assessment_type FOREIGN KEY (assessment_type_id) REFERENCES assessment_types(id),
    CONSTRAINT uk_subject_assessment_term_subject_type UNIQUE (school_id, term_id, subject_id, assessment_type_id),
    CONSTRAINT chk_subject_assessment_active CHECK (active IN (TRUE, FALSE)),
    INDEX idx_subject_assessment_school (school_id),
    INDEX idx_subject_assessment_term (term_id),
    INDEX idx_subject_assessment_subject (subject_id)
);

CREATE TABLE student_scores (
    id BIGINT AUTO_INCREMENT PRIMARY KEY,
    school_id BIGINT NOT NULL,
    term_id BIGINT NOT NULL,
    stream_id BIGINT NOT NULL,
    subject_id BIGINT NOT NULL,
    student_id BIGINT NOT NULL,
    assessment_paper_id BIGINT NULL,
    score DECIMAL(10,2) NOT NULL,
    max_score DECIMAL(10,2) NOT NULL,
    remarks VARCHAR(500) NULL,
    entered_by BIGINT NOT NULL,
    version BIGINT NOT NULL DEFAULT 0,
    created_at DATETIME(6) NOT NULL,
    updated_at DATETIME(6),
    CONSTRAINT fk_score_school FOREIGN KEY (school_id) REFERENCES schools(id),
    CONSTRAINT fk_score_term FOREIGN KEY (term_id) REFERENCES terms(id),
    CONSTRAINT fk_score_stream FOREIGN KEY (stream_id) REFERENCES streams(id),
    CONSTRAINT fk_score_subject FOREIGN KEY (subject_id) REFERENCES subjects(id),
    CONSTRAINT fk_score_student FOREIGN KEY (student_id) REFERENCES students(id),
    CONSTRAINT fk_score_paper FOREIGN KEY (assessment_paper_id) REFERENCES assessment_papers(id),
    CONSTRAINT fk_score_entered_by FOREIGN KEY (entered_by) REFERENCES users(id),
    CONSTRAINT uk_score_student_term_subject_paper UNIQUE (school_id, term_id, student_id, subject_id, assessment_paper_id),
    CONSTRAINT chk_score_value CHECK (score >= 0 AND score <= max_score),
    CONSTRAINT chk_score_max CHECK (max_score > 0),
    INDEX idx_score_school (school_id),
    INDEX idx_score_term (term_id),
    INDEX idx_score_stream (stream_id),
    INDEX idx_score_student (student_id),
    INDEX idx_score_subject (subject_id),
    INDEX idx_score_paper (assessment_paper_id)
);

CREATE TABLE term_grades (
    id BIGINT AUTO_INCREMENT PRIMARY KEY,
    school_id BIGINT NOT NULL,
    term_id BIGINT NOT NULL,
    stream_id BIGINT NOT NULL,
    subject_id BIGINT NOT NULL,
    student_id BIGINT NOT NULL,
    total_raw_score DECIMAL(10,2) NOT NULL,
    total_max_score DECIMAL(10,2) NOT NULL,
    weighted_percentage DECIMAL(5,2) NOT NULL,
    letter_grade VARCHAR(10) NOT NULL,
    gpa DECIMAL(4,2) NOT NULL,
    stream_rank INT NOT NULL,
    computed_at DATETIME(6) NOT NULL,
    computed_by BIGINT NOT NULL,
    created_at DATETIME(6) NOT NULL,
    updated_at DATETIME(6),
    CONSTRAINT fk_term_grade_school FOREIGN KEY (school_id) REFERENCES schools(id),
    CONSTRAINT fk_term_grade_term FOREIGN KEY (term_id) REFERENCES terms(id),
    CONSTRAINT fk_term_grade_stream FOREIGN KEY (stream_id) REFERENCES streams(id),
    CONSTRAINT fk_term_grade_subject FOREIGN KEY (subject_id) REFERENCES subjects(id),
    CONSTRAINT fk_term_grade_student FOREIGN KEY (student_id) REFERENCES students(id),
    CONSTRAINT fk_term_grade_computed_by FOREIGN KEY (computed_by) REFERENCES users(id),
    CONSTRAINT uk_term_grade_term_student_subject UNIQUE (school_id, term_id, student_id, subject_id),
    CONSTRAINT chk_term_grade_percentage CHECK (weighted_percentage >= 0 AND weighted_percentage <= 100),
    CONSTRAINT chk_term_grade_gpa CHECK (gpa >= 0),
    CONSTRAINT chk_term_grade_rank CHECK (stream_rank > 0),
    INDEX idx_term_grade_school (school_id),
    INDEX idx_term_grade_term (term_id),
    INDEX idx_term_grade_stream (stream_id),
    INDEX idx_term_grade_student (student_id)
);
