CREATE TABLE exam_series (
    id BIGINT AUTO_INCREMENT PRIMARY KEY,
    school_id BIGINT NOT NULL,
    term_id BIGINT NOT NULL,
    name VARCHAR(200) NOT NULL,
    start_date DATE NOT NULL,
    end_date DATE NOT NULL,
    registration_opens_on DATE NOT NULL,
    registration_closes_on DATE NOT NULL,
    status VARCHAR(30) NOT NULL DEFAULT 'DRAFT',
    created_by BIGINT NOT NULL,
    created_at DATETIME(6) NOT NULL,
    updated_at DATETIME(6) NULL,

    CONSTRAINT uk_exam_series_school_term_name UNIQUE (school_id, term_id, name),
    CONSTRAINT fk_exam_series_school FOREIGN KEY (school_id) REFERENCES schools(id) ON DELETE CASCADE,
    CONSTRAINT fk_exam_series_term FOREIGN KEY (term_id) REFERENCES terms(id) ON DELETE CASCADE,
    CONSTRAINT fk_exam_series_created_by FOREIGN KEY (created_by) REFERENCES users(id),
    CONSTRAINT chk_exam_series_status CHECK (status IN ('DRAFT', 'REGISTRATION_OPEN', 'REGISTRATION_CLOSED', 'COMPLETED')),
    CONSTRAINT chk_exam_series_dates CHECK (start_date <= end_date AND registration_opens_on <= registration_closes_on),
    INDEX idx_exam_series_school (school_id),
    INDEX idx_exam_series_term (term_id),
    INDEX idx_exam_series_school_status (school_id, status)
);

CREATE TABLE exam_registrations (
    id BIGINT AUTO_INCREMENT PRIMARY KEY,
    school_id BIGINT NOT NULL,
    exam_series_id BIGINT NOT NULL,
    student_id BIGINT NOT NULL,
    subject_id BIGINT NOT NULL,
    assessment_paper_id BIGINT NOT NULL,
    candidate_number VARCHAR(20) NOT NULL,
    class_level_id BIGINT NOT NULL,
    stream_id BIGINT NOT NULL,
    status VARCHAR(20) NOT NULL DEFAULT 'REGISTERED',
    reason VARCHAR(500) NULL,
    registered_by BIGINT NOT NULL,
    version BIGINT NOT NULL DEFAULT 0,
    created_at DATETIME(6) NOT NULL,
    updated_at DATETIME(6) NULL,

    CONSTRAINT uk_exam_reg_school_series_student_paper UNIQUE (school_id, exam_series_id, student_id, assessment_paper_id),
    CONSTRAINT uk_exam_reg_school_series_candidate UNIQUE (school_id, exam_series_id, candidate_number),
    CONSTRAINT fk_exam_reg_school FOREIGN KEY (school_id) REFERENCES schools(id) ON DELETE CASCADE,
    CONSTRAINT fk_exam_reg_series FOREIGN KEY (exam_series_id) REFERENCES exam_series(id) ON DELETE CASCADE,
    CONSTRAINT fk_exam_reg_student FOREIGN KEY (student_id) REFERENCES students(id) ON DELETE CASCADE,
    CONSTRAINT fk_exam_reg_subject FOREIGN KEY (subject_id) REFERENCES subjects(id),
    CONSTRAINT fk_exam_reg_paper FOREIGN KEY (assessment_paper_id) REFERENCES assessment_papers(id),
    CONSTRAINT fk_exam_reg_class_level FOREIGN KEY (class_level_id) REFERENCES class_levels(id),
    CONSTRAINT fk_exam_reg_stream FOREIGN KEY (stream_id) REFERENCES streams(id),
    CONSTRAINT fk_exam_reg_registered_by FOREIGN KEY (registered_by) REFERENCES users(id),
    CONSTRAINT chk_exam_reg_status CHECK (status IN ('REGISTERED', 'WITHDRAWN', 'DEBARRED')),
    INDEX idx_exam_reg_school (school_id),
    INDEX idx_exam_reg_series (exam_series_id),
    INDEX idx_exam_reg_student (student_id),
    INDEX idx_exam_reg_school_series (school_id, exam_series_id),
    INDEX idx_exam_reg_candidate (school_id, exam_series_id, candidate_number)
);
